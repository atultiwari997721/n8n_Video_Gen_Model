import os
import datetime
import random
from github import Github
from github import Auth
from google import genai
from google.genai import types

def generate_coding_problem(api_key):
    """Generates a random Python or JS coding problem using Gemini."""
    if not api_key:
        raise ValueError("GEMINI_API_KEY is missing.")
        
    client = genai.Client(api_key=api_key)
    
    language = random.choice(["Python", "JavaScript"])
    difficulty = random.choice(["Easy", "Medium", "Hard"])
    
    prompt = f"""
    You are an expert software engineering interviewer. 
    Create a unique, interesting {difficulty} level LeetCode-style coding problem to be solved in {language}.
    
    Format the response strictly in Markdown:
    # Problem Title
    
    ## Description
    (problem description)
    
    ## Examples
    (2-3 examples with input/output)
    
    ## Solution ({language})
    ```{'python' if language == 'Python' else 'javascript'}
    // write the optimal solution here
    ```
    
    ## Complexity
    Time: O(?)
    Space: O(?)
    """
    
    response = client.models.generate_content(
        model='gemini-3.1-flash-lite',
        contents=prompt,
    )
    
    title_line = response.text.split('\n')[0]
    safe_title = title_line.replace('#', '').strip().replace(' ', '-').lower()
    
    return safe_title, response.text

def run_github_bot(api_key=None, github_pat=None):
    """Main execution block for the GitHub Bot."""
    print("Starting GitHub Automation Bot...")
    pat = github_pat or os.environ.get("GITHUB_PAT")
    
    if not pat:
        print("GITHUB_PAT not found. Skipping GitHub automation.")
        return
        
    try:
        # Authenticate
        auth = Auth.Token(pat)
        g = Github(auth=auth)
        user = g.get_user()
        
        repo_name = "daily-coding-problems"
        
        # Get or create repository
        try:
            repo = user.get_repo(repo_name)
            print(f"Found repository: {repo.full_name}")
        except Exception:
            print(f"Creating repository: {repo_name}")
            repo = user.create_repo(
                repo_name, 
                description="Daily automated coding problems generated by AI.",
                private=False,
                auto_init=True
            )
            
        # Generate problem
        print("Generating coding problem via Gemini...")
        safe_title, content = generate_coding_problem(api_key)
        
        # Create file
        date_str = datetime.datetime.now().strftime("%Y-%m-%d")
        file_path = f"problems/{date_str}-{safe_title}.md"
        
        print(f"Pushing to GitHub: {file_path}")
        repo.create_file(
            path=file_path,
            message=f"Add daily problem: {safe_title}",
            content=content,
            branch="main"
        )
        print("Successfully pushed to GitHub!")
        
    except Exception as e:
        print(f"GitHub Bot Error: {e}")

if __name__ == "__main__":
    run_github_bot()
